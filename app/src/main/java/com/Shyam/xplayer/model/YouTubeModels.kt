package com.Shyam.xplayer.model

enum class DownloadFormatType {
    VIDEO_MP4,
    AUDIO_HIGH_SPEED
}

enum class DownloadStatus {
    IDLE,
    DOWNLOADING,
    PAUSED,
    COMPLETED,
    FAILED
}

data class YouTubeSubtitle(
    val language: String,
    val languageCode: String,
    val subtitleUrl: String,
    val isAutoGenerated: Boolean = false
)

data class YouTubeVideoQuality(
    val qualityLabel: String,
    val height: Int,
    val format: String = "MP4",
    val approximateSizeBytes: Long = 0L,
    val streamUrl: String
)

data class YouTubeAudioQuality(
    val qualityLabel: String,
    val bitrateKbps: Int,
    val format: String,
    val approximateSizeBytes: Long = 0L,
    val streamUrl: String
)

data class YouTubeVideoItem(
    val id: String,
    val title: String,
    val author: String,
    val durationMs: Long,
    val viewsCount: String = "",
    val thumbnailUrl: String = "",
    val streamUrl: String,
    val videoQualities: List<YouTubeVideoQuality> = emptyList(),
    val audioQualities: List<YouTubeAudioQuality> = emptyList(),
    val subtitles: List<YouTubeSubtitle> = emptyList()
)
